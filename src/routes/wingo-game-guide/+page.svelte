		<h2><span class="n">3.</span>What is Big and Small in Wingo?</h2>
		<p>
			“Big” and “Small” describe the range of the result digit: <strong>Small = 0 to 4</strong>,
			<strong>Big = 5 to 9</strong>. Big/Small is the most beginner-friendly market because it covers half of all
			digits — you win whenever the result falls in your half (except platform-specific rules). Notice that
			<b>0 and 5 belong to both markets</b> (0 is Small, 5 is Big), which is why some platforms treat draws of
			0 or 5 specially.
		</p>

		<h2><span class="n">4.</span>How a Period Works (Step by Step)</h2>
		<ol>
			<li>A new <strong>period number</strong> starts with a visible countdown (e.g. 30 seconds).</li>
			<li>You choose your market — colour, Big/Small or number — and enter an amount.</li>
			<li>You confirm the bet <strong>before the countdown reaches zero</strong>.</li>
			<li>The result digit is drawn at random and the period closes.</li>
			<li>Winning bets are credited; losing bets are collected. Then the next period begins.</li>
		</ol>

